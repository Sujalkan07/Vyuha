CREATE TABLE attendee_passes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    pass_code VARCHAR(32) NOT NULL,
    holder_label VARCHAR(160),
    status VARCHAR(20) NOT NULL DEFAULT 'ISSUED',
    last_gate_id BIGINT,
    last_zone_id BIGINT,
    last_scanned_at TIMESTAMP,
    last_scanned_by_id BIGINT,
    last_scanned_by_name VARCHAR(120),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pass_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_pass_gate FOREIGN KEY (last_gate_id) REFERENCES infrastructure_elements (id) ON DELETE SET NULL,
    CONSTRAINT fk_pass_zone FOREIGN KEY (last_zone_id) REFERENCES functional_zones (id) ON DELETE SET NULL,
    CONSTRAINT fk_pass_scanned_by FOREIGN KEY (last_scanned_by_id) REFERENCES app_users (id) ON DELETE SET NULL,
    CONSTRAINT uq_attendee_pass_event_code UNIQUE (event_id, pass_code)
);

CREATE INDEX idx_attendee_passes_event ON attendee_passes (event_id, status, id);

CREATE TABLE occupancy_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    zone_id BIGINT,
    gate_id BIGINT,
    count_value INTEGER NOT NULL,
    data_source VARCHAR(30) NOT NULL,
    recorded_by_id BIGINT,
    recorded_by VARCHAR(120) NOT NULL,
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    note VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_occ_reading_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_occ_reading_zone FOREIGN KEY (zone_id) REFERENCES functional_zones (id) ON DELETE SET NULL,
    CONSTRAINT fk_occ_reading_gate FOREIGN KEY (gate_id) REFERENCES infrastructure_elements (id) ON DELETE SET NULL,
    CONSTRAINT fk_occ_reading_user FOREIGN KEY (recorded_by_id) REFERENCES app_users (id) ON DELETE SET NULL
);

CREATE INDEX idx_occupancy_readings_event_src
    ON occupancy_readings (event_id, data_source, zone_id, recorded_at DESC, id DESC);

CREATE TABLE monitoring_alert_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    zone_id BIGINT,
    warning_threshold_pct DOUBLE PRECISION NOT NULL DEFAULT 80.0,
    critical_threshold_pct DOUBLE PRECISION NOT NULL DEFAULT 95.0,
    stale_after_minutes INTEGER NOT NULL DEFAULT 15,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_alert_rule_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_alert_rule_zone FOREIGN KEY (zone_id) REFERENCES functional_zones (id) ON DELETE CASCADE
);

CREATE INDEX idx_monitoring_rules_event ON monitoring_alert_rules (event_id, zone_id);

CREATE TABLE monitoring_alert_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    zone_id BIGINT,
    data_source VARCHAR(30) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    alert_type VARCHAR(40) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    triggered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    acknowledged_by_id BIGINT,
    acknowledged_by VARCHAR(120),
    acknowledged_at TIMESTAMP,
    resolved_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_alert_event_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_alert_event_zone FOREIGN KEY (zone_id) REFERENCES functional_zones (id) ON DELETE SET NULL,
    CONSTRAINT fk_alert_event_ack_user FOREIGN KEY (acknowledged_by_id) REFERENCES app_users (id) ON DELETE SET NULL
);

CREATE INDEX idx_monitoring_alerts_event
    ON monitoring_alert_events (event_id, data_source, resolved_at, triggered_at DESC, id DESC);
