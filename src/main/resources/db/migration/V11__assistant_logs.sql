CREATE TABLE assistant_interaction_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT,
    user_id BIGINT,
    mode VARCHAR(40) NOT NULL,
    prompt VARCHAR(2000) NOT NULL,
    response_text CLOB NOT NULL,
    citations_json CLOB,
    proposed_action_json CLOB,
    confirmed_by_user BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assistant_log_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_assistant_log_user FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE SET NULL
);

CREATE INDEX idx_assistant_logs_event
    ON assistant_interaction_logs (event_id, created_at DESC, id DESC);

CREATE INDEX idx_assistant_logs_user
    ON assistant_interaction_logs (user_id, created_at DESC);
