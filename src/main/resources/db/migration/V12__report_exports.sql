CREATE TABLE report_exports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    exported_by_id BIGINT,
    exported_by_name VARCHAR(120) NOT NULL,
    export_format VARCHAR(16) NOT NULL,
    export_scope VARCHAR(60) NOT NULL,
    filename VARCHAR(255) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    summary_note VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_report_export_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_report_export_user FOREIGN KEY (exported_by_id) REFERENCES app_users (id) ON DELETE SET NULL
);

CREATE INDEX idx_report_exports_event
    ON report_exports (event_id, created_at DESC, id DESC);
