CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(180) NOT NULL,
    category VARCHAR(40) NOT NULL,
    status VARCHAR(30) NOT NULL,
    start_date_time TIMESTAMP,
    end_date_time TIMESTAMP,
    schedule_timeline VARCHAR(2000),
    expected_attendance INTEGER,
    location_name VARCHAR(200),
    location_address VARCHAR(500),
    description VARCHAR(2000),
    organizer_id BIGINT NOT NULL,
    assigned_reviewer_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_events_organizer FOREIGN KEY (organizer_id) REFERENCES app_users (id),
    CONSTRAINT fk_events_reviewer FOREIGN KEY (assigned_reviewer_id) REFERENCES app_users (id)
);

CREATE INDEX idx_events_status ON events (status);
CREATE INDEX idx_events_category ON events (category);
CREATE INDEX idx_events_start_date ON events (start_date_time);
CREATE INDEX idx_events_organizer ON events (organizer_id);
CREATE INDEX idx_events_reviewer ON events (assigned_reviewer_id);

CREATE TABLE event_checklist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    item_key VARCHAR(80) NOT NULL,
    section_name VARCHAR(100) NOT NULL,
    title VARCHAR(220) NOT NULL,
    guidance_note VARCHAR(1000),
    status VARCHAR(30) NOT NULL,
    assignee_name VARCHAR(120),
    evidence_notes VARCHAR(1500),
    reviewer_signed_off BOOLEAN NOT NULL DEFAULT FALSE,
    signed_off_by_id BIGINT,
    signed_off_at TIMESTAMP,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_checklist_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_checklist_signer FOREIGN KEY (signed_off_by_id) REFERENCES app_users (id)
);

CREATE INDEX idx_checklist_event_order ON event_checklist_items (event_id, sort_order, id);

CREATE TABLE safety_review_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    reviewer_id BIGINT NOT NULL,
    review_status VARCHAR(40) NOT NULL,
    findings_summary VARCHAR(3000) NOT NULL,
    organizer_response VARCHAR(2000),
    responded_by_id BIGINT,
    responded_at TIMESTAMP,
    reviewed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_review_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_review_reviewer FOREIGN KEY (reviewer_id) REFERENCES app_users (id),
    CONSTRAINT fk_review_responder FOREIGN KEY (responded_by_id) REFERENCES app_users (id)
);

CREATE INDEX idx_reviews_event_time ON safety_review_records (event_id, reviewed_at DESC, id DESC);

CREATE TABLE supporting_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    stored_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(120) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    document_note VARCHAR(500),
    uploaded_by_id BIGINT NOT NULL,
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_doc_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_doc_uploader FOREIGN KEY (uploaded_by_id) REFERENCES app_users (id)
);

CREATE INDEX idx_docs_event_time ON supporting_documents (event_id, uploaded_at DESC, id DESC);
