CREATE TABLE venue_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL UNIQUE,
    workspace_mode VARCHAR(30) NOT NULL DEFAULT 'INTERACTIVE_MAP',
    sample_map_key VARCHAR(80),
    custom_vector_filename VARCHAR(255),
    custom_vector_json CLOB,
    blueprint_original_filename VARCHAR(255),
    blueprint_stored_filename VARCHAR(255),
    blueprint_content_type VARCHAR(120),
    blueprint_file_size_bytes BIGINT,
    blueprint_width_px INTEGER,
    blueprint_height_px INTEGER,
    boundary_wkt CLOB,
    calibration_json CLOB,
    pixels_per_meter DOUBLE PRECISION,
    scale_verified BOOLEAN NOT NULL DEFAULT FALSE,
    distortion_warning BOOLEAN NOT NULL DEFAULT FALSE,
    orthographic_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    grid_snap_meters DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_venue_plan_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE
);

CREATE TABLE exclusion_areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_plan_id BIGINT NOT NULL,
    label VARCHAR(160) NOT NULL,
    exclusion_type VARCHAR(40) NOT NULL,
    polygon_wkt CLOB NOT NULL,
    notes VARCHAR(500),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_exclusion_venue_plan FOREIGN KEY (venue_plan_id) REFERENCES venue_plans (id) ON DELETE CASCADE
);

CREATE INDEX idx_exclusion_venue_plan ON exclusion_areas (venue_plan_id, sort_order, id);
