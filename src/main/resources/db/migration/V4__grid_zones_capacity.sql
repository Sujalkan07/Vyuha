CREATE TABLE venue_grid_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_plan_id BIGINT NOT NULL UNIQUE,
    cell_size_meters DOUBLE PRECISION NOT NULL DEFAULT 5.0,
    origin_x DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    origin_y DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    rotation_deg DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_grid_config_venue_plan FOREIGN KEY (venue_plan_id) REFERENCES venue_plans (id) ON DELETE CASCADE
);

CREATE TABLE functional_zones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_plan_id BIGINT NOT NULL,
    zone_code VARCHAR(32) NOT NULL,
    name VARCHAR(160) NOT NULL,
    zone_type VARCHAR(40) NOT NULL,
    color_hex VARCHAR(16) NOT NULL,
    polygon_wkt CLOB NOT NULL,
    grid_cell_refs_json CLOB,
    is_isolated BOOLEAN NOT NULL DEFAULT FALSE,
    notes VARCHAR(500),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_zone_venue_plan FOREIGN KEY (venue_plan_id) REFERENCES venue_plans (id) ON DELETE CASCADE,
    CONSTRAINT uq_zone_code_per_plan UNIQUE (venue_plan_id, zone_code)
);

CREATE INDEX idx_functional_zones_plan ON functional_zones (venue_plan_id, sort_order, id);

CREATE TABLE capacity_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL UNIQUE,
    official_venue_limit INTEGER,
    official_limit_source VARCHAR(255),
    entry_throughput_per_min DOUBLE PRECISION,
    ingress_window_minutes INTEGER,
    exit_throughput_per_min DOUBLE PRECISION,
    egress_window_minutes INTEGER,
    holding_buffer_capacity INTEGER NOT NULL DEFAULT 0,
    review_status VARCHAR(30) NOT NULL DEFAULT 'PENDING_REVIEW',
    governing_constraint VARCHAR(40) NOT NULL DEFAULT 'INCOMPLETE',
    preliminary_capacity INTEGER,
    notes VARCHAR(2000),
    reviewer_notes VARCHAR(2000),
    verified_by_id BIGINT,
    verified_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_capacity_review_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_capacity_review_verifier FOREIGN KEY (verified_by_id) REFERENCES app_users (id) ON DELETE SET NULL
);

CREATE TABLE zone_density_assumptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capacity_review_id BIGINT NOT NULL,
    functional_zone_id BIGINT NOT NULL,
    density_persons_per_sqm DOUBLE PRECISION,
    source_citation VARCHAR(300),
    approved_by_name VARCHAR(150),
    approved_at TIMESTAMP,
    review_status VARCHAR(30) NOT NULL DEFAULT 'PENDING_REVIEW',
    reviewer_note VARCHAR(1000),
    verified_by_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assumption_review FOREIGN KEY (capacity_review_id) REFERENCES capacity_reviews (id) ON DELETE CASCADE,
    CONSTRAINT fk_assumption_zone FOREIGN KEY (functional_zone_id) REFERENCES functional_zones (id) ON DELETE CASCADE,
    CONSTRAINT fk_assumption_verifier FOREIGN KEY (verified_by_id) REFERENCES app_users (id) ON DELETE SET NULL,
    CONSTRAINT uq_assumption_review_zone UNIQUE (capacity_review_id, functional_zone_id)
);

CREATE INDEX idx_assumptions_review ON zone_density_assumptions (capacity_review_id);
