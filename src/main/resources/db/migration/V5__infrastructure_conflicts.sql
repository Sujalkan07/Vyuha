CREATE TABLE infrastructure_elements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_plan_id BIGINT NOT NULL,
    element_uid VARCHAR(36) NOT NULL,
    element_type VARCHAR(40) NOT NULL,
    label VARCHAR(160) NOT NULL,
    center_x DOUBLE PRECISION NOT NULL,
    center_y DOUBLE PRECISION NOT NULL,
    width_m DOUBLE PRECISION NOT NULL,
    height_m DOUBLE PRECISION NOT NULL,
    rotation_deg DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    footprint_wkt CLOB NOT NULL,
    throughput_persons_per_min DOUBLE PRECISION,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    metadata_json CLOB,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_infra_venue_plan FOREIGN KEY (venue_plan_id) REFERENCES venue_plans (id) ON DELETE CASCADE,
    CONSTRAINT uq_infra_uid_per_plan UNIQUE (venue_plan_id, element_uid)
);

CREATE INDEX idx_infra_elements_plan ON infrastructure_elements (venue_plan_id, sort_order, id);

CREATE TABLE layout_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_plan_id BIGINT NOT NULL,
    revision_number INTEGER NOT NULL,
    command_type VARCHAR(40) NOT NULL,
    summary VARCHAR(200) NOT NULL,
    snapshot_json CLOB NOT NULL,
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    created_by_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_revision_venue_plan FOREIGN KEY (venue_plan_id) REFERENCES venue_plans (id) ON DELETE CASCADE,
    CONSTRAINT fk_revision_user FOREIGN KEY (created_by_id) REFERENCES app_users (id) ON DELETE SET NULL,
    CONSTRAINT uq_revision_number_per_plan UNIQUE (venue_plan_id, revision_number)
);

CREATE INDEX idx_layout_revisions_plan ON layout_revisions (venue_plan_id, revision_number);

CREATE TABLE conflict_findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_plan_id BIGINT NOT NULL,
    finding_key VARCHAR(180) NOT NULL,
    conflict_type VARCHAR(50) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    measured_value VARCHAR(120),
    location_x DOUBLE PRECISION,
    location_y DOUBLE PRECISION,
    involved_element_ids VARCHAR(300),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    review_status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    reviewer_note VARCHAR(1000),
    reviewed_by_id BIGINT,
    reviewed_at TIMESTAMP,
    resolved_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conflict_venue_plan FOREIGN KEY (venue_plan_id) REFERENCES venue_plans (id) ON DELETE CASCADE,
    CONSTRAINT fk_conflict_reviewer FOREIGN KEY (reviewed_by_id) REFERENCES app_users (id) ON DELETE SET NULL,
    CONSTRAINT uq_conflict_key_per_plan UNIQUE (venue_plan_id, finding_key)
);

CREATE INDEX idx_conflict_findings_plan ON conflict_findings (venue_plan_id, active, severity);
