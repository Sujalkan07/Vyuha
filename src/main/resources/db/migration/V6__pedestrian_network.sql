CREATE TABLE pathway_nodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_plan_id BIGINT NOT NULL,
    node_uid VARCHAR(36) NOT NULL,
    node_type VARCHAR(40) NOT NULL,
    label VARCHAR(160) NOT NULL,
    x DOUBLE PRECISION NOT NULL,
    y DOUBLE PRECISION NOT NULL,
    linked_zone_id BIGINT,
    linked_infra_id BIGINT,
    notes VARCHAR(500),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pathway_node_venue_plan FOREIGN KEY (venue_plan_id) REFERENCES venue_plans (id) ON DELETE CASCADE,
    CONSTRAINT fk_pathway_node_zone FOREIGN KEY (linked_zone_id) REFERENCES functional_zones (id) ON DELETE SET NULL,
    CONSTRAINT fk_pathway_node_infra FOREIGN KEY (linked_infra_id) REFERENCES infrastructure_elements (id) ON DELETE SET NULL,
    CONSTRAINT uq_pathway_node_uid_per_plan UNIQUE (venue_plan_id, node_uid)
);

CREATE INDEX idx_pathway_nodes_plan ON pathway_nodes (venue_plan_id, sort_order, id);

CREATE TABLE pathway_edges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_plan_id BIGINT NOT NULL,
    edge_uid VARCHAR(36) NOT NULL,
    from_node_id BIGINT NOT NULL,
    to_node_id BIGINT NOT NULL,
    label VARCHAR(160),
    network_layer VARCHAR(40) NOT NULL,
    width_m DOUBLE PRECISION NOT NULL,
    length_m DOUBLE PRECISION NOT NULL,
    direction VARCHAR(20) NOT NULL DEFAULT 'BIDIRECTIONAL',
    polyline_wkt CLOB NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    notes VARCHAR(500),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pathway_edge_venue_plan FOREIGN KEY (venue_plan_id) REFERENCES venue_plans (id) ON DELETE CASCADE,
    CONSTRAINT fk_pathway_edge_from_node FOREIGN KEY (from_node_id) REFERENCES pathway_nodes (id) ON DELETE CASCADE,
    CONSTRAINT fk_pathway_edge_to_node FOREIGN KEY (to_node_id) REFERENCES pathway_nodes (id) ON DELETE CASCADE,
    CONSTRAINT uq_pathway_edge_uid_per_plan UNIQUE (venue_plan_id, edge_uid)
);

CREATE INDEX idx_pathway_edges_plan ON pathway_edges (venue_plan_id, network_layer, active);

CREATE TABLE bottleneck_findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_plan_id BIGINT NOT NULL,
    finding_key VARCHAR(180) NOT NULL,
    finding_type VARCHAR(50) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    measured_value VARCHAR(160),
    threshold_note VARCHAR(250),
    location_x DOUBLE PRECISION,
    location_y DOUBLE PRECISION,
    involved_node_ids VARCHAR(300),
    involved_edge_ids VARCHAR(300),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    review_status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    reviewer_note VARCHAR(1000),
    reviewed_by_id BIGINT,
    reviewed_at TIMESTAMP,
    resolved_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_bottleneck_venue_plan FOREIGN KEY (venue_plan_id) REFERENCES venue_plans (id) ON DELETE CASCADE,
    CONSTRAINT fk_bottleneck_reviewer FOREIGN KEY (reviewed_by_id) REFERENCES app_users (id) ON DELETE SET NULL,
    CONSTRAINT uq_bottleneck_key_per_plan UNIQUE (venue_plan_id, finding_key)
);

CREATE INDEX idx_bottleneck_findings_plan ON bottleneck_findings (venue_plan_id, active, severity);
