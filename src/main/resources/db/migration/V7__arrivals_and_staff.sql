CREATE TABLE arrival_wave_intervals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    target_gate_id BIGINT,
    label VARCHAR(120),
    start_minute INTEGER NOT NULL,
    end_minute INTEGER NOT NULL,
    expected_arrivals INTEGER NOT NULL,
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_wave_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_wave_target_gate FOREIGN KEY (target_gate_id) REFERENCES infrastructure_elements (id) ON DELETE SET NULL
);

CREATE INDEX idx_arrival_waves_event ON arrival_wave_intervals (event_id, start_minute, end_minute, id);

CREATE TABLE staff_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    role_type VARCHAR(30) NOT NULL,
    contact_phone VARCHAR(40),
    certifications VARCHAR(500),
    notes VARCHAR(500),
    user_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_staff_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_staff_user FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE SET NULL
);

CREATE INDEX idx_staff_members_event ON staff_members (event_id, role_type, id);

CREATE TABLE staff_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    staff_id BIGINT NOT NULL,
    zone_id BIGINT,
    infra_id BIGINT,
    post_label VARCHAR(160),
    shift_start TIMESTAMP NOT NULL,
    shift_end TIMESTAMP NOT NULL,
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assignment_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_assignment_staff FOREIGN KEY (staff_id) REFERENCES staff_members (id) ON DELETE CASCADE,
    CONSTRAINT fk_assignment_zone FOREIGN KEY (zone_id) REFERENCES functional_zones (id) ON DELETE SET NULL,
    CONSTRAINT fk_assignment_infra FOREIGN KEY (infra_id) REFERENCES infrastructure_elements (id) ON DELETE SET NULL
);

CREATE INDEX idx_staff_assignments_event ON staff_assignments (event_id, shift_start, id);
CREATE INDEX idx_staff_assignments_staff ON staff_assignments (staff_id, shift_start);

CREATE TABLE staffing_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL UNIQUE,
    min_security_per_active_gate INTEGER NOT NULL DEFAULT 2,
    min_staff_per_public_zone INTEGER NOT NULL DEFAULT 2,
    min_medical_staff_total INTEGER NOT NULL DEFAULT 2,
    min_supervisors_total INTEGER NOT NULL DEFAULT 1,
    attendees_per_staff_ratio INTEGER NOT NULL DEFAULT 150,
    shift_window_minutes INTEGER NOT NULL DEFAULT 60,
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_staffing_target_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE
);

CREATE TABLE incident_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    zone_id BIGINT,
    assigned_staff_id BIGINT,
    reported_by_id BIGINT,
    reported_by_name VARCHAR(120),
    reported_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    severity VARCHAR(20) NOT NULL,
    description VARCHAR(1500) NOT NULL,
    response_taken VARCHAR(1500),
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    resolved_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_incident_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_incident_zone FOREIGN KEY (zone_id) REFERENCES functional_zones (id) ON DELETE SET NULL,
    CONSTRAINT fk_incident_staff FOREIGN KEY (assigned_staff_id) REFERENCES staff_members (id) ON DELETE SET NULL,
    CONSTRAINT fk_incident_reporter FOREIGN KEY (reported_by_id) REFERENCES app_users (id) ON DELETE SET NULL
);

CREATE INDEX idx_incident_logs_event ON incident_logs (event_id, reported_at DESC, id DESC);
