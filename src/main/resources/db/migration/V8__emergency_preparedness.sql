CREATE TABLE emergency_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    asset_type VARCHAR(30) NOT NULL,
    label VARCHAR(160) NOT NULL,
    geometry_wkt CLOB NOT NULL,
    min_width_m DOUBLE PRECISION,
    capacity_notes VARCHAR(500),
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_emergency_asset_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE
);

CREATE INDEX idx_emergency_assets_event ON emergency_assets (event_id, asset_type, id);

CREATE TABLE emergency_contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    agency_name VARCHAR(160) NOT NULL,
    contact_name VARCHAR(150) NOT NULL,
    phone VARCHAR(50) NOT NULL,
    role VARCHAR(120) NOT NULL,
    priority_order INTEGER NOT NULL DEFAULT 1,
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_emergency_contact_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE
);

CREATE INDEX idx_emergency_contacts_event ON emergency_contacts (event_id, priority_order, id);
