CREATE TABLE layout_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    version_number INTEGER NOT NULL,
    label VARCHAR(160) NOT NULL,
    notes VARCHAR(500),
    serialized_layout_json CLOB NOT NULL,
    thumbnail_png_path VARCHAR(255),
    created_by_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_layout_snapshot_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_layout_snapshot_user FOREIGN KEY (created_by_id) REFERENCES app_users (id) ON DELETE SET NULL,
    CONSTRAINT uq_layout_snapshot_version UNIQUE (event_id, version_number)
);

CREATE INDEX idx_layout_snapshots_event ON layout_snapshots (event_id, version_number);

CREATE TABLE simulation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    snapshot_id BIGINT NOT NULL,
    label VARCHAR(160),
    scenario_type VARCHAR(40) NOT NULL,
    random_seed BIGINT NOT NULL,
    duration_seconds INTEGER NOT NULL,
    agent_count INTEGER NOT NULL,
    config_json CLOB NOT NULL,
    metrics_summary_json CLOB NOT NULL,
    frame_stream_path VARCHAR(255),
    created_by_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sim_run_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_sim_run_snapshot FOREIGN KEY (snapshot_id) REFERENCES layout_snapshots (id) ON DELETE CASCADE,
    CONSTRAINT fk_sim_run_user FOREIGN KEY (created_by_id) REFERENCES app_users (id) ON DELETE SET NULL
);

CREATE INDEX idx_simulation_runs_event ON simulation_runs (event_id, created_at DESC, id DESC);
CREATE INDEX idx_simulation_runs_snapshot ON simulation_runs (snapshot_id, scenario_type, random_seed);
